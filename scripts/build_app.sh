#!/bin/zsh
# Build PraatTypen.app: a menu-bar app bundle that starts PraatTypen from the
# virtualenv in this checkout.
#
# The bundle is a thin wrapper, not a redistributable app -- it points back at
# this folder, so do not move the checkout after building (rebuild instead).
# The point of the bundle is macOS identity: microphone and accessibility
# permissions get granted to PraatTypen instead of to your terminal.

set -euo pipefail

APP_HOME="${0:A:h:h}"
# In /Applications so Spotlight and Launchpad find it; the bundle still points
# back at this checkout. Override with PRAATTYPEN_APP for another location.
APP="${PRAATTYPEN_APP:-/Applications/AirQuote.app}"
CONTENTS="$APP/Contents"
VERSION="0.1.0"

if [[ ! -x "$APP_HOME/.venv/bin/python" ]]; then
  print -u2 "Geen virtualenv gevonden in $APP_HOME/.venv"
  print -u2 "Maak hem eerst: python3 -m venv .venv && .venv/bin/python -m pip install -r requirements.txt"
  exit 1
fi

# Where the venv's interpreter really lives, and which stdlib belongs to it.
PY_REAL="$(readlink -f "$APP_HOME/.venv/bin/python")"
PY_HOME="$("$APP_HOME/.venv/bin/python" -c 'import sys; print(sys.base_prefix)')"
PY_TAG="$("$APP_HOME/.venv/bin/python" -c 'import sys; print(f"python{sys.version_info.major}.{sys.version_info.minor}")')"
SITE_PACKAGES="$APP_HOME/.venv/lib/$PY_TAG/site-packages"

# macOS derives an app's identity from the path of the running executable. Exec
# the framework interpreter directly and every PyObjC process reports itself as
# org.python.python -- so microphone and accessibility rights land on "Python",
# shared with every other Python on this Mac, which is exactly what the bundle
# is supposed to prevent. Running a copy of the interpreter from inside the
# bundle makes the same process report as nl.praattypen.app.
PY_STUB="$PY_HOME/Resources/Python.app/Contents/MacOS/Python"
if [[ ! -x "$PY_STUB" ]]; then
  PY_STUB="$PY_REAL"
fi

rm -rf "$APP"
mkdir -p "$CONTENTS/MacOS" "$CONTENTS/Resources"
cp "$PY_STUB" "$CONTENTS/MacOS/airquote-python"

if ! "$APP_HOME/.venv/bin/python" "$APP_HOME/scripts/make_icon.py" \
     "$CONTENTS/Resources/AirQuote.icns" >/dev/null; then
  print -u2 "Waarschuwing: icoon genereren mislukt; de Dock toont een blanco tegel."
fi

cat > "$CONTENTS/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>AirQuote</string>
  <key>CFBundleDisplayName</key><string>AirQuote</string>
  <key>CFBundleIdentifier</key><string>nl.airquote.app</string>
  <key>CFBundleExecutable</key><string>AirQuote</string>
  <key>CFBundleIconFile</key><string>AirQuote</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>$VERSION</string>
  <key>CFBundleVersion</key><string>$VERSION</string>
  <key>LSMinimumSystemVersion</key><string>11.0</string>
  <!-- Launched without focus, so PraatTypen never takes the front app away
       from you at login. The Dock icon is added afterwards at runtime by
       appearance.apply_activation_policy (config: dock_icon), which promotes
       the app without that activation. -->
  <key>LSUIElement</key><true/>
  <key>NSInputMonitoringUsageDescription</key>
  <string>AirQuote watches its hotkey to know when you want to dictate.</string>
  <key>NSAppleEventsUsageDescription</key>
  <string>AirQuote pastes your dictation at the cursor with Cmd+V.</string>
  <key>NSMicrophoneUsageDescription</key>
  <string>AirQuote records your voice while you hold the hotkey and turns it into text on this Mac.</string>
  <!-- Only needed because this checkout lives in a TCC-protected folder
       (Documents, Desktop or Downloads). Without it macOS blocks the app from
       reading its own virtualenv, and does so without explaining why. -->
  <key>NSDocumentsFolderUsageDescription</key>
  <string>AirQuote runs from this folder and needs to read its own code.</string>
  <key>NSDesktopFolderUsageDescription</key>
  <string>AirQuote runs from this folder and needs to read its own code.</string>
  <key>NSDownloadsFolderUsageDescription</key>
  <string>AirQuote runs from this folder and needs to read its own code.</string>
</dict>
</plist>
PLIST

cat > "$CONTENTS/MacOS/AirQuote" <<SHIM
#!/bin/zsh
# Generated by scripts/build_app.sh -- edit that, not this.
set -u

APP_HOME="$APP_HOME"
BUNDLE_MACOS="\${0:A:h}"
LOG_DIR="\$HOME/Library/Logs"
mkdir -p "\$LOG_DIR"

# Anything Python writes outside our logger (tracebacks, MLX and Hugging Face
# chatter) has nowhere to go without a terminal. Truncated per launch so it
# always describes the run you are looking at.
exec > "\$LOG_DIR/PraatTypen.out.log" 2>&1

# The interpreter copy cannot find its own stdlib or the virtualenv from where
# it now sits, so both are passed in explicitly.
export PYTHONHOME="$PY_HOME"
export PYTHONPATH="$APP_HOME:$SITE_PACKAGES"

cd "\$APP_HOME"
exec "\$BUNDLE_MACOS/airquote-python" -m praattypen.main run
SHIM

chmod +x "$CONTENTS/MacOS/AirQuote" "$CONTENTS/MacOS/airquote-python"

# Ad-hoc signing gives the bundle a stable identity, so macOS remembers the
# permissions you grant it. A rebuild changes that identity and resets the
# permissions -- but the Python code lives outside the bundle, so you only
# rebuild when this script itself changes.
codesign --force --sign - "$CONTENTS/MacOS/airquote-python" >/dev/null 2>&1
codesign --force --sign - "$APP" >/dev/null 2>&1 || \
  print -u2 "Waarschuwing: ad-hoc ondertekenen mislukt; permissies blijven mogelijk niet bewaard."

print "Gebouwd: $APP"
print
print "Nu nog eenmalig:"
print "  1. Start de app (dubbelklik of: open '$APP')."
print "  2. Systeeminstellingen -> Privacy en beveiliging -> Microfoon: zet AirQuote aan."
print "  3. Idem bij Toegankelijkheid en bij Invoermonitoring."
print "  4. Automatisch starten: Systeeminstellingen -> Algemeen -> Inloggen -> '+' -> AirQuote.app"
